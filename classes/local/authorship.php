EOT;

    /**
     * Whether authorship features are enabled (plagiarism_dixeo plugin only).
     *
     * @return bool
     */
    public static function is_enabled(): bool {
        $value = get_config('plagiarism_dixeo', 'enabled');
        if ($value !== false && $value !== null) {
            return ((int) $value) !== 0;
        }
        return true;
    }

    /**
     * Integration entry point: evaluate text for authorship, optionally create/update record and quiz HTML.
     *
     * When disabled, returns score 100 and no record/quiz. When enabled, gets confidence score;
     * if below threshold, creates or updates record with generated quiz and returns quiz HTML.
     *
     * @param string $text Text to evaluate for authorship.
     * @param array $context Keys: component, area, itemid, userid; optional render_options for quiz form.
     * @return array{score: float, record: object|null, quiz_html: string}
     */
    public static function check(string $text, array $context = []): array {
        if (!self::is_enabled()) {
            return ['score' => (float) self::CONFIDENCE_MAX, 'record' => null, 'quiz_html' => ''];
        }
        $uploadfiles = $context['uploadfiles'] ?? [];
        $usefiles = !empty($uploadfiles) && is_array($uploadfiles);
        $initial = $usefiles
            ? self::get_confidence_score_with_files($uploadfiles, $context)
            : self::get_confidence_score($text, $context);
        $score = (float) $initial['score'];
        $explanation = (string) ($initial['explanation'] ?? '');
        $record = null;
        $quizhtml = '';
        if (self::is_quiz_required($score)) {
            $options = array_merge($context, ['initial_confidence' => $score]);
            $quiz = $usefiles
                ? self::generate_quiz_with_files($uploadfiles, $options)
                : self::generate_quiz($text, $options);
            $userid = (int) ($context['userid'] ?? 0);
            $component = (string) ($context['component'] ?? '');
            $area = (string) ($context['area'] ?? '');
            $itemid = (int) ($context['itemid'] ?? 0);
            $existing = author_storage::get_record_by_context($userid, $component, $area, $itemid);
            $frombackend = [
                'initial_confidence'  => $score,
                'initial_explanation'  => $explanation,
                'quiz_data' => $quiz,
            ];
            if ($existing) {
                author_storage::update_initial($existing->id, $frombackend);
                $record = author_storage::get_record($existing->id);
            } else {
                $record = author_storage::create_record($userid, $component, $area, $itemid, $frombackend);
            }
            if ($record) {
                $quizhtml = self::render_quiz_form($record, $context['render_options'] ?? []);
            }
        }
        return ['score' => $score, 'record' => $record, 'quiz_html' => $quizhtml];
    }

    /**
     * Get a 0–100 confidence score for the authorship of a text (via AI).
     *
     * @param string $text The text to evaluate.
     * @param array $options Optional options.
     * @return array{score: float, explanation: string} Confidence and short reasoning.
     */
    public static function get_confidence_score(string $text, array $options = []): array {
        $structure = [
            'type'       => 'object',
            'properties' => [
                'confidence' => ['type' => 'number'],
                'explanation' => ['type' => 'string'],
            ],
            'required'   => ['confidence', 'explanation'],
        ];
        $ai = new ai('Dixeo authorship', ['authorship' => 'initial_confidence']);
        $result = $ai->send_request(
            self::PROMPT_INITIAL_CONFIDENCE,
            ['text' => $text],
            [],
            $structure,
            null
        );
        if (!$result->success || empty($result->data['confidence'])) {
            return [
                'score'       => self::confidence_fallback_when_unavailable(),
                'explanation' => '',
            ];
        }
        $score = (float) $result->data['confidence'];
        $score = max(self::CONFIDENCE_MIN, min(self::CONFIDENCE_MAX, $score));
        $explanation = isset($result->data['explanation']) ? trim((string) $result->data['explanation']) : '';
        return ['score' => $score, 'explanation' => $explanation];
    }

    /** Fallback confidence when AI is unavailable or returns invalid data (neutral 50). */
    private const CONFIDENCE_FALLBACK = 50.0;

    /**
     * Confidence value returned when AI is unavailable or returns invalid data.
     *
     * @return float
     */
    private static function confidence_fallback_when_unavailable(): float {
        return self::CONFIDENCE_FALLBACK;
    }

    /**
     * Get a 0–100 confidence score when the submission is in uploaded files (Assistants API file_search).
     *
     * @param array $files Array of \stored_file instances.
     * @param array $options Optional context.
     * @return array{score: float, explanation: string} Confidence and short reasoning.
     */
    public static function get_confidence_score_with_files(array $files, array $options = []): array {
        $structure = [
            'type'       => 'object',
            'properties' => [
                'confidence' => ['type' => 'number'],
                'explanation' => ['type' => 'string'],
            ],
            'required'   => ['confidence', 'explanation'],
        ];
        $usertext = 'Use the file_search tool now to read the attached document in full. Then assign a confidence score from 0 to 100 (0 = certainly AI-generated, 100 = certainly human-written) and respond with a JSON object only: {"confidence": number, "explanation": "your short reasoning"}.' . "\n";
        $ai = new ai('Dixeo authorship', ['authorship' => 'initial_confidence']);
        $result = $ai->send_request_with_files(
            self::PROMPT_INITIAL_CONFIDENCE_FILES,
            $usertext,
            $files,
            $structure,
            null
        );
        if (!$result->success || empty($result->data['confidence'])) {
            return [
                'score'       => self::confidence_fallback_when_unavailable(),
                'explanation' => '',
            ];
        }
        $score = (float) $result->data['confidence'];
        $score = max(self::CONFIDENCE_MIN, min(self::CONFIDENCE_MAX, $score));
        $explanation = isset($result->data['explanation']) ? trim((string) $result->data['explanation']) : '';
        return ['score' => $score, 'explanation' => $explanation];
    }

    /**
     * Get the confidence threshold (0–100) below which a quiz is required. Reads from plagiarism_dixeo only.
     *
     * @param array $overrides Optional keys: authorship_threshold.
     * @return float
     */
    public static function get_confidence_threshold(array $overrides = []): float {
        $value = null;
        if (isset($overrides['authorship_threshold']) && $overrides['authorship_threshold'] !== '' && $overrides['authorship_threshold'] !== null) {
            $value = $overrides['authorship_threshold'];
        }
        if ($value === null) {
            $value = get_config('plagiarism_dixeo', 'authorship_threshold');
        }
        $int = ($value !== false && $value !== null) ? (int) $value : (int) self::DEFAULT_CONFIDENCE_THRESHOLD;
        return (float) max(self::CONFIDENCE_MIN, min(self::CONFIDENCE_MAX, $int));
    }

    /**
     * Get the number of questions to generate per type (from plagiarism_dixeo settings).
     * True/false: 1–5 (default 1). Multiple choice and open: 0–5.
     *
     * @param array $overrides Optional config overrides.
     * @return array{true_false: int, multiple_choice: int, open: int}
     */
    public static function get_question_counts(array $overrides = []): array {
        $read = function ($key, $default, int $min = 0) use ($overrides) {
            if (isset($overrides[$key]) && $overrides[$key] !== '' && $overrides[$key] !== null) {
                $n = (int) $overrides[$key];
                return max($min, min(5, $n));
            }
            $v = get_config('plagiarism_dixeo', $key);
            $n = ($v !== false && $v !== null) ? (int) $v : $default;
            return max($min, min(5, $n));
        };
        return [
            'true_false'      => $read('authorship_count_true_false', self::DEFAULT_COUNT_TRUE_FALSE, 1),
            'multiple_choice' => $read('authorship_count_multiple_choice', self::DEFAULT_COUNT_MULTIPLE_CHOICE, 0),
            'open'            => $read('authorship_count_open', self::DEFAULT_COUNT_OPEN, 0),
        ];
    }

    /**
     * Map (component, area) to the module class that provides get_{area}_authorship_content.
     *
     * @param string $component e.g. 'mod_assign'
     * @param string $area e.g. 'submission'
     * @return string|null Fully qualified class name or null
     */
    public static function get_module_class_for_area(string $component, string $area): ?string {
        $map = [
            'mod_assign' => assign::class,
        ];
        $class = $map[$component] ?? null;
        if ($class === null || $area === '') {
            return null;
        }
        $method = 'get_' . $area . '_authorship_content';
        return method_exists($class, $method) ? $class : null;
    }

    /**
     * Get content (text and itemid) for authorship check from a component/area/id.
     *
     * @param string $component e.g. mod_assign
     * @param string $area e.g. submission
     * @param int $id Area-specific id (e.g. course module id)
     * @param int|null $userid Optional user id; when null uses current $USER->id
     * @return array{text: string, itemid: int, files?: \stored_file[]}
     */
    public static function get_content_for_check(string $component, string $area, int $id, ?int $userid = null): array {
        global $USER;

        $class = self::get_module_class_for_area($component, $area);
        if ($class === null || $id <= 0) {
            return ['text' => '', 'itemid' => 0];
        }

        $method = 'get_' . $area . '_authorship_content';
        if (!method_exists($class, $method)) {
            return ['text' => '', 'itemid' => 0];
        }

        $uid = $userid !== null ? (int) $userid : (int) $USER->id;
        $result = $class::$method($id, $uid);
        if (!is_array($result) || !array_key_exists('text', $result) || !array_key_exists('itemid', $result)) {
            return ['text' => '', 'itemid' => 0];
        }

        $out = [
            'text'   => (string) ($result['text'] ?? ''),
            'itemid' => (int) ($result['itemid'] ?? 0),
        ];
        if (!empty($result['files']) && is_array($result['files'])) {
            $out['files'] = $result['files'];
        }
        return $out;
    }

    /**
     * Evaluate initial authorship (no record creation). Used by observer (sync) or scheduled task (async).
     *
     * @param string $component e.g. mod_assign
     * @param string $area e.g. submission
     * @param int $id Area-specific id (e.g. cmid for assign)
     * @param int $userid User whose submission to evaluate
     * @return array{initial_confidence: float, initial_explanation: string, quiz_data: array|null}
     */
    public static function evaluate_initial(string $component, string $area, int $id, int $userid): array {
        if (!self::is_enabled()) {
            return [
                'initial_confidence' => (float) self::CONFIDENCE_MAX,
                'initial_explanation' => '',
                'quiz_data' => null,
            ];
        }

        $content = self::get_content_for_check($component, $area, $id, $userid);
        $uploadfiles = $content['files'] ?? [];
        $usefiles = !empty($uploadfiles) && is_array($uploadfiles);
        $text = trim((string) ($content['text'] ?? ''));
        if (!$usefiles && $text === '') {
            return [
                'initial_confidence'  => (float) self::confidence_fallback_when_unavailable(),
                'initial_explanation'  => get_string('authorship_no_content', 'plagiarism_dixeo'),
                'quiz_data'            => null,
            ];
        }
        $initial = $usefiles
            ? self::get_confidence_score_with_files($uploadfiles, ['userid' => $userid])
            : self::get_confidence_score($content['text'], ['userid' => $userid]);
        $score = (float) $initial['score'];
        $explanation = (string) ($initial['explanation'] ?? '');
        if ($explanation === '') {
            $explanation = get_string('authorship_explanation_fallback', 'plagiarism_dixeo');
        }

        $threshold = self::get_confidence_threshold();

        $quizdata = null;
        if (self::is_quiz_required($score, $threshold)) {
            $options = ['initial_confidence' => $score, 'userid' => $userid];
            $quizdata = $usefiles
                ? self::generate_quiz_with_files($uploadfiles, $options)
                : self::generate_quiz($content['text'], $options);
        }

        return [
            'initial_confidence'  => $score,
            'initial_explanation' => $explanation,
            'quiz_data'           => $quizdata,
        ];
    }

    /**
     * Check whether the given confidence score requires a quiz.
     *
     * @param float $score Confidence score (0–100).
     * @param float|null $threshold Optional threshold; uses config if null.
     * @return bool
     */
    public static function is_quiz_required(float $score, ?float $threshold = null): bool {
        $threshold = $threshold ?? self::get_confidence_threshold();
        if ($threshold <= 0) {
            return true;
        }
        return $score < $threshold;
    }

    /**
     * Generate quiz questions when confidence is below threshold (via AI).
     *
     * @param string $text The original text.
     * @param array $options Optional: initial_confidence, _overrides.
     * @return array Quiz data (version, questions, meta).
     */
    public static function generate_quiz(string $text, array $options = []): array {
        $overrides = $options['_overrides'] ?? [];
        $counts = self::get_question_counts($overrides);
        $total = $counts['true_false'] + $counts['multiple_choice'] + $counts['open'];
        if ($total === 0) {
            return [
                'version'   => 1,
                'questions' => [],
                'meta'      => ['generated' => false],
            ];
        }

        $prompt = self::build_generate_quiz_prompt($counts);
        $structure = [
            'type'       => 'object',
            'properties' => [
                'questions' => [
                    'type'  => 'array',
                    'items' => [
                        'type'       => 'object',
                        'properties' => [
                            'id'      => ['type' => 'string'],
                            'type'    => ['type' => 'string'],
                            'text'    => ['type' => 'string'],
                            'options' => ['type' => 'array'],
                        ],
                        'required'   => ['id', 'type', 'text'],
                    ],
                ],
            ],
            'required'   => ['questions'],
        ];
        $data = ['text' => $text];
        if (isset($options['initial_confidence'])) {
            $data['initial_confidence'] = (string) $options['initial_confidence'];
        }
        $ai = new ai('Dixeo authorship', ['authorship' => 'generate_quiz']);
        $result = $ai->send_request(
            $prompt,
            $data,
            [],
            $structure,
            null
        );
        if (!$result->success || empty($result->data['questions']) || !is_array($result->data['questions'])) {
            return [
                'version'   => 1,
                'questions' => [],
                'meta'      => ['generated' => false],
            ];
        }
        $normalized = self::normalize_quiz_questions($result->data['questions']);
        $questions = self::filter_questions_by_counts($normalized, $counts);
        return [
            'version'   => 1,
            'questions' => $questions,
            'meta'      => ['generated' => true],
        ];
    }

    /**
     * Build counts line and requirements block for quiz generation prompts.
     *
     * @param array{true_false: int, multiple_choice: int, open: int} $counts
     * @param bool $fromfiles If true, wording is for document/file context.
     * @return array{0: string, 1: string} [counts_line, requirements_block]
     */
    private static function build_quiz_prompt_parts(array $counts, bool $fromfiles = false): array {
        $total = $counts['true_false'] + $counts['multiple_choice'] + $counts['open'];
        $parts = [];
        if ($counts['true_false'] > 0) {
            $parts[] = $counts['true_false'] . ' of type "true_false"';
        }
        if ($counts['multiple_choice'] > 0) {
            $parts[] = $counts['multiple_choice'] . ' of type "multiple_choice"';
        }
        if ($counts['open'] > 0) {
            $parts[] = $counts['open'] . ' of type "open"';
        }
        $countsline = 'Generate exactly ' . $total . ' verification question(s): ' . implode(', ', $parts) . '.';

        $requirements = [];
        $i = 1;
        if ($counts['true_false'] > 0) {
            $requirements[] = $i . '. true_false: key "text" (statement about the ' . ($fromfiles ? 'document' : 'text') . '), key "correct" (1 for true, 0 for false).';
            $i++;
        }
        if ($counts['multiple_choice'] > 0) {
            $requirements[] = $i . '. multiple_choice: key "text" (the question), key "options" (array of exactly 4 objects with "value" and "text"), key "correct" (the "value" of the correct option).';
            $i++;
        }
        if ($counts['open'] > 0) {
            $requirements[] = $i . '. open: key "text" (a question only the author could answer in detail from ' . ($fromfiles ? 'the document' : 'their own writing') . ').';
        }
        $requirementsblock = 'Requirements:' . "\n" . implode("\n", $requirements);
        return [$countsline, $requirementsblock];
    }

    /**
     * Build the generate-quiz prompt (text-based).
     *
     * @param array{true_false: int, multiple_choice: int, open: int} $counts
     * @return string
     */
    private static function build_generate_quiz_prompt(array $counts): string {
        [$countsline, $requirementsblock] = self::build_quiz_prompt_parts($counts, false);
        return str_replace(
            ['{counts}', '{requirements}'],
            [$countsline, $requirementsblock],
            self::PROMPT_GENERATE_QUIZ_TPL
        );
    }

    /**
     * Build the generate-quiz prompt when content comes from uploaded files.
     *
     * @param array{true_false: int, multiple_choice: int, open: int} $counts
     * @return string
     */
    private static function build_generate_quiz_from_files_prompt(array $counts): string {
        [$countsline, $requirementsblock] = self::build_quiz_prompt_parts($counts, true);
        return str_replace(
            ['{counts}', '{requirements}'],
            [$countsline, $requirementsblock],
            self::PROMPT_GENERATE_QUIZ_FROM_FILES_TPL
        );
    }

    /**
     * Generate quiz questions from uploaded document files (Assistants API file_search).
     *
     * @param array $files Array of \stored_file instances.
     * @param array $options Optional: initial_confidence, _overrides.
     * @return array Quiz data (version, questions, meta).
     */
    public static function generate_quiz_with_files(array $files, array $options = []): array {
        $overrides = $options['_overrides'] ?? [];
        $counts = self::get_question_counts($overrides);
        $total = $counts['true_false'] + $counts['multiple_choice'] + $counts['open'];
        if ($total === 0) {
            return [
                'version'   => 1,
                'questions' => [],
                'meta'      => ['generated' => false],
            ];
        }
        $prompt = self::build_generate_quiz_from_files_prompt($counts);
        $structure = [
            'type'       => 'object',
            'properties' => [
                'questions' => [
                    'type'  => 'array',
                    'items' => [
                        'type'       => 'object',
                        'properties' => [
                            'id'      => ['type' => 'string'],
                            'type'    => ['type' => 'string'],
                            'text'    => ['type' => 'string'],
                            'options' => ['type' => 'array'],
                        ],
                        'required'   => ['id', 'type', 'text'],
                    ],
                ],
            ],
            'required'   => ['questions'],
        ];
        $usertext = 'Generate the verification questions from the attached document. Use the file_search tool to read the document first; then create questions based only on its actual content.';
        if (isset($options['initial_confidence'])) {
            $usertext .= ' Initial confidence (0–100, human vs AI): ' . (string) $options['initial_confidence'];
        }
        $usertext .= '.';
        $ai = new ai('Dixeo authorship', ['authorship' => 'generate_quiz']);
        $result = $ai->send_request_with_files(
            $prompt,
            $usertext,
            $files,
            $structure,
            null
        );
        if (!$result->success || empty($result->data['questions']) || !is_array($result->data['questions'])) {
            return [
                'version'   => 1,
                'questions' => [],
                'meta'      => ['generated' => false],
            ];
        }
        $normalized = self::normalize_quiz_questions($result->data['questions']);
        $questions = self::filter_questions_by_counts($normalized, $counts);
        return [
            'version'   => 1,
            'questions' => $questions,
            'meta'      => ['generated' => true],
        ];
    }

    /**
     * Filter normalized questions to match the requested counts per type.
     *
     * @param array $normalized Normalized question array.
     * @param array{true_false: int, multiple_choice: int, open: int} $counts
     * @return array
     */
    private static function filter_questions_by_counts(array $normalized, array $counts): array {
        $take = [
            self::QUESTION_TYPE_TRUE_FALSE      => $counts['true_false'],
            self::QUESTION_TYPE_MULTIPLE_CHOICE => $counts['multiple_choice'],
            self::QUESTION_TYPE_OPEN            => $counts['open'],
        ];
        $collected = [
            self::QUESTION_TYPE_TRUE_FALSE      => [],
            self::QUESTION_TYPE_MULTIPLE_CHOICE => [],
            self::QUESTION_TYPE_OPEN            => [],
        ];
        foreach ($normalized as $q) {
            $type = $q['type'] ?? self::QUESTION_TYPE_OPEN;
            if (isset($collected[$type]) && count($collected[$type]) < $take[$type]) {
                $collected[$type][] = $q;
            }
        }
        return array_merge(
            $collected[self::QUESTION_TYPE_TRUE_FALSE],
            $collected[self::QUESTION_TYPE_MULTIPLE_CHOICE],
            $collected[self::QUESTION_TYPE_OPEN]
        );
    }

    /**
     * Normalize AI-generated questions to renderer shape (id, type, text, options for MC).
     *
     * @param array $raw Array of question objects.
     * @return array
     */
    private static function normalize_quiz_questions(array $raw): array {
        $out = [];
        foreach ($raw as $i => $q) {
            $id = $q['id'] ?? ('q' . $i);
            $type = $q['type'] ?? self::QUESTION_TYPE_OPEN;
            $type = self::map_question_type($type);
            $normalized = [
                'id'   => (string) $id,
                'type' => $type,
                'text' => trim((string) ($q['text'] ?? '')),
            ];
            if ($type === self::QUESTION_TYPE_MULTIPLE_CHOICE && !empty($q['options']) && is_array($q['options'])) {
                $normalized['options'] = [];
                foreach ($q['options'] as $j => $opt) {
                    if (is_array($opt)) {
                        $normalized['options'][] = [
                            'value' => (string) ($opt['value'] ?? $opt['text'] ?? $j),
                            'text'  => (string) ($opt['text'] ?? $opt['value'] ?? ''),
                        ];
                    } else {
                        $normalized['options'][] = ['value' => (string) $j, 'text' => (string) $opt];
                    }
                }
            }
            if ($type === self::QUESTION_TYPE_TRUE_FALSE && isset($q['correct'])) {
                $normalized['correct'] = (int) (filter_var($q['correct'], FILTER_VALIDATE_BOOLEAN) ? 1 : 0);
            } elseif ($type === self::QUESTION_TYPE_MULTIPLE_CHOICE && isset($q['correct'])) {
                $normalized['correct'] = (string) $q['correct'];
            }
            if ($normalized['text'] !== '') {
                $out[] = $normalized;
            }
        }
        return $out;
    }

    /**
     * Map AI question type string to our constant.
     *
     * @param string $type
     * @return string
     */
    private static function map_question_type(string $type): string {
        $t = strtolower($type);
        if ($t === 'true_false' || $t === 'truefalse') {
            return self::QUESTION_TYPE_TRUE_FALSE;
        }
        if ($t === 'multiple_choice' || $t === 'multiplechoice' || $t === 'mc') {
            return self::QUESTION_TYPE_MULTIPLE_CHOICE;
        }
        return self::QUESTION_TYPE_OPEN;
    }

    /**
     * Render the quiz as an HTML form that can be submitted.
     *
     * @param object|array $recordOrQuizData DB record (with quiz_data, optionally id) or decoded quiz array.
     * @param array $options form_action_url, submit_label, record_id, css_class.
     * @return string HTML fragment.
     */
    public static function render_quiz_form($recordorquizdata, array $options = []): string {
        $recordid = $options['record_id'] ?? null;
        $action = $options['form_action_url'] ?? '';
        $submitlabel = $options['submit_label'] ?? get_string('authorship_submit_quiz', 'plagiarism_dixeo');
        $cssclass = $options['css_class'] ?? 'plagiarism-dixeo-authorship-quiz';

        if (is_object($recordorquizdata) && isset($recordorquizdata->quiz_data)) {
            $quiz = is_string($recordorquizdata->quiz_data)
                ? json_decode($recordorquizdata->quiz_data, true)
                : $recordorquizdata->quiz_data;
            if ($recordid === null && isset($recordorquizdata->id)) {
                $recordid = (int) $recordorquizdata->id;
            }
        } else {
            $quiz = is_array($recordorquizdata) ? $recordorquizdata : ['questions' => []];
        }

        $questions = $quiz['questions'] ?? [];
        $html = [];
        $html[] = '<form class="' . s($cssclass) . '" method="post" action="' . s($action) . '" data-authorship-record-id="' . (int) $recordid . '">';
        $html[] = '<input type="hidden" name="authorship_record_id" value="' . (int) $recordid . '" />';

        foreach ($questions as $index => $q) {
            $html[] = self::render_quiz_question($q, $index);
        }

        $html[] = '<div class="authorship-quiz-actions"><button type="submit" class="btn btn-primary">' . s($submitlabel) . '</button></div>';
        $html[] = '</form>';
        return implode("\n", $html);
    }

    /**
     * Render a single quiz question (true/false, multiple_choice, open).
     *
     * @param array $question Must contain type, text; for multiple_choice, options array.
     * @param int $index Question index for name/id.
     * @return string HTML fragment.
     */
    private static function render_quiz_question(array $question, int $index): string {
        $type = $question['type'] ?? self::QUESTION_TYPE_OPEN;
        $text = $question['text'] ?? '';
        $id = $question['id'] ?? ('q' . $index);
        $name = 'authorship_q[' . s($id) . ']';
        $out = [];

        $out[] = '<div class="authorship-question authorship-question-' . s($type) . '" data-question-id="' . s($id) . '">';
        $out[] = '<label class="authorship-question-text">' . s($text) . '</label>';

        switch ($type) {
            case self::QUESTION_TYPE_TRUE_FALSE:
                $out[] = '<div class="authorship-options">';
                $out[] = '<label><input type="radio" name="' . $name . '" value="1" /> ' . get_string('true', 'plagiarism_dixeo') . '</label>';
                $out[] = '<label><input type="radio" name="' . $name . '" value="0" /> ' . get_string('false', 'plagiarism_dixeo') . '</label>';
                $out[] = '</div>';
                break;
            case self::QUESTION_TYPE_MULTIPLE_CHOICE:
                $opts = $question['options'] ?? [];
                $out[] = '<div class="authorship-options">';
                foreach ($opts as $optindex => $opt) {
                    $optval = is_array($opt) ? ($opt['value'] ?? $opt['text'] ?? $optindex) : $opt;
                    $opttext = is_array($opt) ? ($opt['text'] ?? (string) $optval) : (string) $opt;
                    $out[] = '<label><input type="radio" name="' . $name . '" value="' . s($optval) . '" /> ' . s($opttext) . '</label>';
                }
                $out[] = '</div>';
                break;
            case self::QUESTION_TYPE_OPEN:
            default:
                $out[] = '<textarea name="' . $name . '" rows="4" class="form-control"></textarea>';
                break;
        }

        $out[] = '</div>';
        return implode("\n", $out);
    }

    /**
     * Compute objective grade (0–100) from correct answers for true_false and multiple_choice only.
     *
     * @param object $record Authorship record with quiz_data (questions may have "correct" key).
     * @param array $responses Question id => user answer.
     * @return float|null Grade 0–100 or null if no gradeable questions.
     */
    public static function compute_quiz_grade(object $record, array $responses): ?float {
        $quiz = is_string($record->quiz_data ?? '') ? json_decode($record->quiz_data, true) : ($record->quiz_data ?? []);
        $questions = $quiz['questions'] ?? [];
        $total = 0;
        $correct = 0;
        foreach ($questions as $q) {
            if (!isset($q['correct'])) {
                continue;
            }
            $id = $q['id'] ?? null;
            if ($id === null || $id === '') {
                continue;
            }
            $total++;
            $user = $responses[$id] ?? $responses[(string) $id] ?? null;
            $expected = $q['correct'];
            $type = $q['type'] ?? self::QUESTION_TYPE_OPEN;
            $isright = false;
            if ($type === self::QUESTION_TYPE_TRUE_FALSE) {
                $normalized = $user === true || $user === 1 || $user === '1' ? 1 : 0;
                $isright = ($normalized === (int) $expected);
            } elseif ($type === self::QUESTION_TYPE_MULTIPLE_CHOICE) {
                $isright = ((string) $user === (string) $expected);
            }
            if ($isright) {
                $correct++;
            }
        }
        if ($total === 0) {
            return null;
        }
        return round(($correct / $total) * 100, 2);
    }

    /**
     * Evaluate final confidence and objective grade from quiz responses (via AI).
     *
     * @param object $record Authorship record (with initial_confidence, quiz_data).
     * @param array $responses Decoded quiz responses (question id => answer).
     * @return array{final_confidence: float, grade: float|null, final_explanation: string}
     */
    public static function evaluate_final_confidence(object $record, array $responses): array {
        $structure = [
            'type'       => 'object',
            'properties' => [
                'grade'             => ['type' => ['number', 'null']],
                'quiz_explanation'  => ['type' => 'string'],
                'final_confidence'  => ['type' => 'number'],
                'final_explanation' => ['type' => 'string'],
            ],
            'required'   => ['grade', 'quiz_explanation', 'final_confidence', 'final_explanation'],
        ];
        $quiz = is_string($record->quiz_data ?? '') ? json_decode($record->quiz_data, true) : ($record->quiz_data ?? []);
        $questions = $quiz['questions'] ?? [];
        $data = [
            'initial_confidence' => (string) ($record->initial_confidence ?? 0),
            'questions'         => json_encode($questions, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT),
            'answers'            => json_encode($responses, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT),
        ];
        $ai = new ai('Dixeo authorship', ['authorship' => 'final_confidence']);
        $result = $ai->send_request(
            self::PROMPT_FINAL_CONFIDENCE,
            $data,
            [],
            $structure,
            null
        );
        $fallback = (float) ($record->initial_confidence ?? 0);
        if (!$result->success || !isset($result->data['final_confidence'])) {
            return [
                'grade'             => self::compute_quiz_grade($record, $responses),
                'quiz_explanation'   => '',
                'final_confidence'  => $fallback,
                'final_explanation' => '',
            ];
        }
        $score = (float) $result->data['final_confidence'];
        $finalconfidence = max(self::CONFIDENCE_MIN, min(self::CONFIDENCE_MAX, $score));
        $grade = null;
        if (isset($result->data['grade']) && $result->data['grade'] !== null) {
            $g = (float) $result->data['grade'];
            $grade = max(0, min(100, round($g, 2)));
        }
        $quizexplanation = isset($result->data['quiz_explanation'])
            ? trim((string) $result->data['quiz_explanation'])
            : '';
        $finalexplanation = isset($result->data['final_explanation'])
            ? trim((string) $result->data['final_explanation'])
            : '';
        return [
            'grade'             => $grade,
            'quiz_explanation'  => $quizexplanation,
            'final_confidence'  => $finalconfidence,
            'final_explanation' => $finalexplanation,
        ];
    }

    /**
     * Evaluate verification quiz (no DB). Returns result for caller to store via author_storage::update_record.
     *
     * @param string|array $quizdata JSON string or decoded quiz_data array
     * @param array $responses Question id => answer
     * @param float|null $initialconfidence Initial confidence (0–100)
     * @return array{final_confidence: float, quiz_grade: float|null, quiz_explanation: string, final_explanation: string}
     */
    public static function evaluate_verify($quizdata, array $responses, ?float $initialconfidence = null): array {
        $record = (object) [
            'quiz_data'          => is_string($quizdata) ? $quizdata : json_encode($quizdata),
            'initial_confidence' => $initialconfidence ?? 0,
        ];
        $evaluation = self::evaluate_final_confidence($record, $responses);
        $grade = $evaluation['grade'] ?? self::compute_quiz_grade($record, $responses);
        return [
            'final_confidence'  => (float) $evaluation['final_confidence'],
            'quiz_grade'        => $grade,
            'quiz_explanation'  => (string) ($evaluation['quiz_explanation'] ?? ''),
            'final_explanation' => (string) ($evaluation['final_explanation'] ?? ''),
        ];
    }
